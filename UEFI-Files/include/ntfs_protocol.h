/* Protocol Message Types */
#define NTFS_MSG_REGISTER_ROLE     1
#define NTFS_MSG_CREATE_WINDOW     2
#define NTFS_MSG_WINDOW_CREATED    3
#define NTFS_MSG_DESTROY_WINDOW    4
#define NTFS_MSG_WINDOW_DESTROYED  5
#define NTFS_MSG_SET_GEOMETRY      6
#define NTFS_MSG_DAMAGE            7
#define NTFS_MSG_MOUSE_EVENT       8
#define NTFS_MSG_KEY_EVENT         9
#define NTFS_MSG_FOCUS_WINDOW      10
#define NTFS_MSG_CLOSE_WINDOW      11
#define NTFS_MSG_FRAME_READY       12
#define NTFS_MSG_GET_SCREEN_INFO   13
#define NTFS_MSG_SCREEN_INFO       14
