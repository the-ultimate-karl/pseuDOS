/* Client Roles */
#define NTFS_ROLE_CLIENT           0
#define NTFS_ROLE_COMPOSITOR       1
#define NTFS_ROLE_WM               2

/* Mouse Buttons & Flags */
#define NTFS_MOUSE_BTN_LEFT        0x01
#define NTFS_MOUSE_BTN_RIGHT       0x02
#define NTFS_MOUSE_BTN_MIDDLE      0x04
#define NTFS_MOUSE_WHEEL_UP        0x08
#define NTFS_MOUSE_WHEEL_DOWN      0x10

/* Window Flags */
#define NTFS_WIN_NORMAL            0x00
#define NTFS_WIN_FRAMELESS         0x01
#define NTFS_WIN_BACKGROUND        0x02
#define NTFS_WIN_TASKBAR           0x04
#define NTFS_WIN_SPLASH            0x08
#define NTFS_WIN_FIXED_SIZE        0x10

/* Special Key Codes */
#define NTFS_KEY_WIN               0x90

/* Standard 64-byte protocol packet */
typedef struct __attribute__((packed)) {
    uint32_t type;             /* NTFS_MSG_* */
    uint32_t window_id;        /* Target / source window ID */
    int32_t  x;                /* Screen / window position X */
    int32_t  y;                /* Screen / window position Y */
    uint32_t width;            /* Surface width in pixels */
    uint32_t height;           /* Surface height in pixels */
    uint32_t shm_id;           /* Shared memory region handle */
    uint32_t buttons_or_key;   /* Mouse buttons or keyboard ASCII/scancode */
    uint32_t flags;            /* Special window flags */
    char     title[32];        /* Window title or role name */
} ntfs_msg_t;

