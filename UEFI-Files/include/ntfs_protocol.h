/* Basic Primitive Drawing Utilities */
static inline void gfx_draw_pixel(uint32_t *buf, int width, int height, int x, int y, uint32_t color) {
    if (x >= 0 && x < width && y >= 0 && y < height) {
        buf[y * width + x] = color;
    }
}

static inline void gfx_fill_rect(uint32_t *buf, int width, int height, int rx, int ry, int rw, int rh, uint32_t color) {
    int x0 = (rx < 0) ? 0 : rx;
    int y0 = (ry < 0) ? 0 : ry;
    int x1 = (rx + rw > width) ? width : rx + rw;
    int y1 = (ry + rh > height) ? height : ry + rh;

    for (int y = y0; y < y1; y++) {
        uint32_t *row = &buf[y * width];
        for (int x = x0; x < x1; x++) {
            row[x] = color;
        }
    }
}

static inline void gfx_draw_char(uint32_t *buf, int width, int height, int x, int y, char c, uint32_t fg, uint32_t bg, int transparent_bg) {
    if ((unsigned char)c < 32 || (unsigned char)c > 127) c = '?';
    const uint8_t *glyph = g_vga_font_8x16[(unsigned char)c - 32];

    for (int row = 0; row < 16; row++) {
        int py = y + row;
        if (py < 0 || py >= height) continue;
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            int px = x + col;
            if (px < 0 || px >= width) continue;
            if (bits & (0x80 >> col)) {
                buf[py * width + px] = fg;
            } else if (!transparent_bg) {
                buf[py * width + px] = bg;
            }
        }
    }
}

static inline void gfx_draw_string(uint32_t *buf, int width, int height, int x, int y, const char *str, uint32_t fg, uint32_t bg, int transparent_bg) {
    if (!str) return;
    int cur_x = x;
    while (*str) {
        gfx_draw_char(buf, width, height, cur_x, y, *str, fg, bg, transparent_bg);
        cur_x += 8;
        str++;
    }
}

static inline void gfx_draw_bevel(uint32_t *buf, int width, int height, int x, int y, int w, int h, int sunken) {
    uint32_t tl = sunken ? COLOR_BTN_SHADOW : COLOR_BTN_LIGHT;
    uint32_t br = sunken ? COLOR_BTN_LIGHT : COLOR_BTN_DKSHADOW;

    /* Top and Left */
    gfx_fill_rect(buf, width, height, x, y, w, 1, tl);
    gfx_fill_rect(buf, width, height, x, y, 1, h, tl);

    /* Bottom and Right */
    gfx_fill_rect(buf, width, height, x, y + h - 1, w, 1, br);
    gfx_fill_rect(buf, width, height, x + w - 1, y, 1, h, br);
}

/* System-Wide Classic Windows 95 Error / Warning Dialog */
static inline void gfx_draw_error_dialog(uint32_t *buf, int width, int height,
                                         int mx, int my, int mw, int mh,
                                         const char *title,
                                         const char *line1, const char *line2) {
    if (!buf || mw <= 0 || mh <= 0) return;

    /* 1. Base Dialog Background */
    gfx_fill_rect(buf, width, height, mx, my, mw, mh, COLOR_BTN_FACE);

    /* 2. Classic 3D Double Bevel */
    gfx_draw_bevel(buf, width, height, mx, my, mw, mh, 0);
    gfx_fill_rect(buf, width, height, mx + 1, my + 1, mw - 2, 1, COLOR_WHITE);
    gfx_fill_rect(buf, width, height, mx + 1, my + 1, 1, mh - 2, COLOR_WHITE);
    gfx_fill_rect(buf, width, height, mx + 1, my + mh - 2, mw - 2, 1, COLOR_BTN_SHADOW);
    gfx_fill_rect(buf, width, height, mx + mw - 2, my + 1, 1, mh - 2, COLOR_BTN_SHADOW);

    /* 3. Navy Blue Title Bar across top */
    int tb_x = mx + 3;
    int tb_y = my + 3;
    int tb_w = mw - 6;
    int tb_h = 18;
    gfx_fill_rect(buf, width, height, tb_x, tb_y, tb_w, tb_h, COLOR_WIN_TITLE);
    gfx_draw_string(buf, width, height, tb_x + 5, tb_y + 3, (title && title[0]) ? title : "pseuDOS", COLOR_WHITE, 0, 1);

    /* 4. Yellow Warning Triangle Icon */
    int icon_cx = mx + 44;
    int icon_ty = my + 32;
    int icon_h = 44;
    int icon_hw = 26;

    /* Solid bright yellow fill */
    for (int r = 0; r < icon_h; r++) {
        int hw = (r * icon_hw) / icon_h;
        gfx_fill_rect(buf, width, height, icon_cx - hw, icon_ty + r, hw * 2 + 1, 1, 0x00FFCC00);
    }

    /* Thick black outline (2px) */
    for (int r = 0; r < icon_h; r++) {
        int hw = (r * icon_hw) / icon_h;
        gfx_fill_rect(buf, width, height, icon_cx - hw, icon_ty + r, 2, 1, COLOR_BLACK);
        gfx_fill_rect(buf, width, height, icon_cx + hw - 1, icon_ty + r, 2, 1, COLOR_BLACK);
    }
    /* Flat bottom border (2px) */
    gfx_fill_rect(buf, width, height, icon_cx - icon_hw, icon_ty + icon_h - 2, icon_hw * 2 + 1, 2, COLOR_BLACK);

    /* Bold black exclamation mark (!) */
    /* Vertical stem: 4px wide, 16px high */
    gfx_fill_rect(buf, width, height, icon_cx - 2, icon_ty + 13, 4, 16, COLOR_BLACK);
    /* Dot: 4x4 px */
    gfx_fill_rect(buf, width, height, icon_cx - 2, icon_ty + 32, 4, 4, COLOR_BLACK);

    /* 5. Centered Message Text */
    int text_area_x = icon_cx + icon_hw + 12;
    int text_area_w = (mx + mw - 12) - text_area_x;
    if (text_area_w > 0) {
        if (line1 && line1[0] && line2 && line2[0]) {
            int len1 = 0; while (line1[len1]) len1++;
            int tx1 = text_area_x + (text_area_w - len1 * 8) / 2;
            if (tx1 < text_area_x) tx1 = text_area_x;
            gfx_draw_string(buf, width, height, tx1, my + 42, line1, COLOR_BLACK, 0, 1);

            int len2 = 0; while (line2[len2]) len2++;
            int tx2 = text_area_x + (text_area_w - len2 * 8) / 2;
            if (tx2 < text_area_x) tx2 = text_area_x;
            gfx_draw_string(buf, width, height, tx2, my + 62, line2, COLOR_BLACK, 0, 1);
        } else if (line1 && line1[0]) {
            int len1 = 0; while (line1[len1]) len1++;
            int tx1 = text_area_x + (text_area_w - len1 * 8) / 2;
            if (tx1 < text_area_x) tx1 = text_area_x;
            gfx_draw_string(buf, width, height, tx1, my + 52, line1, COLOR_BLACK, 0, 1);
        }
    }

    /* 6. Centered OK Button: 64x22 */
    int btn_w = 64, btn_h = 22;
    int btn_x = mx + (mw - btn_w) / 2;
    int btn_y = my + mh - 30;

    gfx_fill_rect(buf, width, height, btn_x, btn_y, btn_w, btn_h, COLOR_BTN_FACE);
    gfx_draw_bevel(buf, width, height, btn_x, btn_y, btn_w, btn_h, 0);
    gfx_draw_string(buf, width, height, btn_x + 24, btn_y + 3, "OK", COLOR_BLACK, 0, 1);
}

